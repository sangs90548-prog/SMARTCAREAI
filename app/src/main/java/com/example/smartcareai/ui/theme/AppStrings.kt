fun getStringsForLanguage(language: String?): AppStrings {
    return when {
        language == null -> EnglishStrings
        language.contains("தமிழ்") || language.equals("Tamil", ignoreCase = true) -> TamilStrings
        language.contains("हिन्दी") || language.equals("Hindi", ignoreCase = true) -> HindiStrings
        language.contains("Español") || language.equals("Spanish", ignoreCase = true) -> SpanishStrings
        language.contains("Français") || language.equals("French", ignoreCase = true) -> FrenchStrings
        language.contains("Deutsch") || language.equals("German", ignoreCase = true) -> GermanStrings
        language.contains("中文") || language.equals("Mandarin", ignoreCase = true) || language.equals("Chinese", ignoreCase = true) -> MandarinStrings
        else -> EnglishStrings
    }
}

